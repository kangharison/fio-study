/*
 * [한국어 설명] SHA-512 해시 알고리즘 헤더 (sha512.h)
 *
 * === 파일의 역할 ===
 * SHA-512(Secure Hash Algorithm 512-bit, FIPS 180-4) 해시 함수의 공개 API 를
 * 정의한다. SHA-2 계열 중 최대 변종으로 512비트(64바이트) 다이제스트를
 * 생성하며, 1024비트(128바이트) 입력 블록을 80 라운드로 처리한다. 연산 기반은
 * 64비트 워드(Σ0/Σ1/σ0/σ1 회전/시프트, 대형 상수 K[80]) 이라 64비트 플랫폼에서
 * 가장 빠르다. fio 에서는 verify=sha512 모드의 데이터 무결성 검증에 사용된다.
 *
 * === 전체 아키텍처에서의 위치 ===
 * 호출 체인:
 *   verify.c::fill_sha512() / verify_io_u_sha512()
 *     → fio_sha512_init(ctx)
 *     → fio_sha512_update(ctx, data, len)  // 여러 번 호출 가능(스트리밍)
 *     → fio_sha512_final(ctx)              // ctx->buf 에 64바이트 결과 배치
 *   결과 다이제스트는 verify_header.v_sha512 필드(최대 크기)에 저장된다.
 *
 * === 타 모듈과의 연결 ===
 * - sha512.c: 실제 구현(sha512_transform 라운드 루프, 초기 해시 상수 H0~H7).
 * - verify.c: verify=sha512 옵션의 fill/verify 경로.
 * - crc/test.c: --crctest=sha512 벤치마크 등록.
 * - inttypes.h: uint32_t/uint64_t/uint8_t 타입 공급.
 *
 * === 주요 함수/구조체 요약 ===
 * - struct fio_sha512_ctx: SHA-512 스트리밍 계산 상태(H0~H7 + 128비트 카운터 + W[80]).
 * - fio_sha512_init(): 컨텍스트에 FIPS 180-4 초기 해시값(H0~H7) 설정.
 * - fio_sha512_update(): 임의 길이 바이트를 누적 투입 → 1024비트 블록 단위 변환.
 * - fio_sha512_final(): 마지막 블록 패딩(0x80 + 0 + 128비트 길이) 후 buf 에 기록.
 */
#ifndef FIO_SHA512_H
/* [한국어] 헤더 가드 — verify.c / sha512.c / test.c 동시 포함 대비. */
#define FIO_SHA512_H

#include <inttypes.h>
/* [한국어] <inttypes.h> 포함 이유: SHA-512 는 64비트 워드(uint64_t)를 기반으로
 * 하며, 128비트 메시지 길이 카운터를 uint32_t 4개로 표현한다. 고정폭 정수
 * 정의가 필수. uint8_t 는 출력 버퍼와 update 입력 바이트 포인터에 사용. */

/*
 * [한국어] SHA-512 스트리밍 계산 컨텍스트
 * init → update(여러 번) → final 순서로 사용. final 이후 buf 에 64바이트
 * 다이제스트가 배치되며 호출자가 verify_header 로 복사한다.
 */
struct fio_sha512_ctx {
	uint64_t state[8];
	/* [한국어] SHA-512 8개의 64비트 해시 상태 워드(a~h = H0~H7).
	 * 설정자: fio_sha512_init() 이 FIPS 180-4 초기 해시 상수로 초기화.
	 * 읽는 자: sha512_transform() 각 라운드에서 읽고 갱신, final() 이 buf 에 직렬화.
	 * 값 범위: 64비트 부호 없는 정수. 중간 상태라 특별한 불변식은 없음.
	 * 동기화: ctx 는 호출자 스택/힙에 존재하며 잡 스레드 단독 소유 — 락 불필요. */

	uint32_t count[4];
	/* [한국어] 지금까지 투입한 총 비트 수를 128비트로 표현(상위→하위 워드 순).
	 * 설정자: update() 가 투입 바이트 × 8 을 누적, 필요 시 상위 워드로 캐리 전파.
	 * 읽는 자: final() 이 메시지 끝 패딩에 128비트 길이 필드로 직렬화.
	 * 값 범위: 0 ~ 2^128-1(실질 무한). 잡 버퍼 크기가 2^128 바이트를 넘지 않음.
	 * 동기화: 잡 스레드 단독 접근 — 락 불필요. */

	uint8_t *buf;
	/* [한국어] 임시/출력 버퍼 포인터. 호출자가 외부에서 할당(최소 128 바이트).
	 * 설정자: 호출자가 init 전 또는 init 호출 시 ctx->buf = &local_buf[0] 형태로 지정.
	 *        (구현에 따라 init 이 내부 배열로 초기화하는 변종도 있음 — sha512.c 확인.)
	 * 읽는 자: update() 가 블록 미만 잔여 바이트 보관용으로, final() 이 완료 후
	 *         64바이트 다이제스트를 이 버퍼에 기록.
	 * 값 범위: 유효한 최소 128바이트 버퍼 포인터. NULL 금지.
	 * 동기화: 잡 스레드 단독 — 락 불필요. */

	uint64_t W[80];
	/* [한국어] SHA-512 메시지 스케줄 워드 배열(80라운드용).
	 * 설정자: update() 가 1024비트 블록을 16 워드로 로드한 뒤 σ0/σ1 연산으로
	 *        17~80 번째 워드를 파생시켜 채움.
	 * 읽는 자: sha512_transform() 각 라운드 t 에서 W[t] 와 상수 K[t] 를 합성.
	 * 값 범위: 64비트 부호 없는 정수. 라운드 간 값만 의미 있고 라운드 종료 후 재사용.
	 * 동기화: 잡 스레드 단독 — 락 불필요.
	 * 최적화 메모: 일부 구현은 W[16] 링버퍼로 공간을 줄이나, 본 구현은 80 슬롯
	 *            그대로 두어 단순성과 약간의 캐시 지역성을 얻는다. */
};

/*
 * [한국어]
 * fio_sha512_init - SHA-512 컨텍스트 초기화
 *
 * @ctx: 호출자가 소유한 컨텍스트(힙 또는 스택). ctx->buf 는 호출 전 유효한
 *       128바이트 이상 버퍼를 가리켜야 함.
 *
 * 동작: state[0..7] 에 FIPS 180-4 에서 명시한 SHA-512 초기 해시값(소수의 제곱근
 *      소수 부분)을 대입, count[] 를 0 으로 리셋, W[] 는 lazy 초기화(update 에서 채움).
 *
 * 호출 체인: verify.c::fill_sha512()/verify_io_u_sha512() → fio_sha512_init()
 * 실행 컨텍스트: 잡 스레드. 에러: 없음.
 */
void fio_sha512_init(struct fio_sha512_ctx *);

/*
 * [한국어]
 * fio_sha512_update - 임의 길이 바이트를 SHA-512 에 투입
 *
 * @ctx:  초기화된 컨텍스트.
 * @data: 투입할 바이트 버퍼(이미 계산 진행 중인 스트림의 일부).
 * @len:  바이트 수.
 *
 * 동작: 내부 버퍼에 잔여 바이트를 결합해 1024비트 블록이 완성될 때마다
 *      sha512_transform() 호출. count[] 에 len*8 누적. 잔여는 buf 에 보관.
 *
 * 호출 체인: fill_sha512() 에서 verify_header + 사용자 데이터 두 번 호출.
 * 에러: 없음(unsigned int len 상한 4GiB, verify 블록은 이보다 훨씬 작음).
 */
void fio_sha512_update(struct fio_sha512_ctx *, const uint8_t *, unsigned int);

/*
 * [한국어]
 * fio_sha512_final - 마지막 블록 패딩 및 다이제스트 출력
 *
 * @sctx: update 를 완료한 컨텍스트. 성공 후 sctx->buf 앞 64바이트에 해시가 기록됨.
 *
 * 동작: 1) 0x80 바이트와 0 패딩으로 마지막 블록을 112바이트까지 채움.
 *      2) count[] 를 128비트 빅엔디안 길이 필드로 마지막 16바이트에 삽입.
 *      3) 추가 sha512_transform() 호출.
 *      4) state[0..7] 을 빅엔디안으로 직렬화하여 buf[0..63] 에 기록.
 *
 * 호출 후 ctx 는 재사용 금지(재사용 시 다시 init 호출 필요).
 * 실행 컨텍스트: 잡 스레드. 에러: 없음.
 */
void fio_sha512_final(struct fio_sha512_ctx *sctx);

#endif
