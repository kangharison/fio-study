/*
 * [한국어 설명] 해밍 가중치(population count) 소프트웨어 구현 (hweight.c)
 *
 * === 파일의 역할 ===
 * 정수의 비트 중 1로 설정된 개수(Hamming weight = popcount)를 세는 함수 hweight8/32/64 를
 * SWAR(Software-And-Register-Wide) 기법으로 구현한다. SWAR 는 단일 64비트 레지스터를
 * "여러 개의 작은 병렬 카운터"처럼 사용하여 분기/루프 없이 상수 시간 O(1) 으로
 * popcount 를 수행한다. x86-64 의 POPCNT 명령, ARMv8 의 CNT 같은 하드웨어 명령 또는
 * GCC/Clang 의 __builtin_popcount* 가 제공되지 않거나 이식성 있는 폴백이 필요한 코드
 * 경로를 위해 항상 사용 가능한 기본 구현을 제공한다.
 *
 * SWAR 알고리즘의 3단계:
 *   (1) 2-비트 쌍의 1-비트 개수를 각 쌍 내부에 저장:
 *       w = w - ((w >> 1) & 0x5...5);  // 각 2비트 쌍 내 popcount
 *   (2) 4-비트 니블로 확장:
 *       w = (w & 0x3...3) + ((w >> 2) & 0x3...3);
 *   (3) 8-비트 바이트로 확장 후, 상위 자릿수 누적:
 *       w = (w + (w >> 4)) & 0x0F...0F;
 *       w += w >> 8 ... w >> 32;  // 필요 비트 폭까지 누적
 *   (4) 하위 바이트의 누적 합을 마스크로 추출.
 *
 * === 전체 아키텍처에서의 위치 ===
 * fio 내부에서 비트맵/비트셋의 설정된 비트 수 계산에 사용된다. 대표적으로
 * lib/axmap.c(이미 기록된 블록 추적 비트맵), verify.c(CRC 에러 비트 진단 —
 * hweight8 로 XOR 결과의 비트 불일치 개수 카운트), CPU affinity 마스크의 활성 CPU
 * 수 계산 등 여러 위치에서 호출된다. 순수 함수이므로 실행 컨텍스트 무관,
 * 재진입 안전.
 *
 * === 타 모듈과의 연결 ===
 * - hweight.h: 본 파일이 공개하는 세 함수의 프로토타입. BITS_PER_LONG 매크로가
 *   해당 헤더 체인(../arch/*.h → os/os.h) 을 통해 32 또는 64 로 정의됨.
 * - arch/*.h 혹은 컴파일러 플래그: BITS_PER_LONG 정의 출처. 32비트 타겟에서
 *   64비트 곱셈/시프트 폴백이 느릴 수 있으므로 hweight64 를 hweight32 두 번으로 분해.
 * - 호출자: verify.c(비트 오차 진단), lib/axmap.c(비트맵 팝카운트), options.c 등.
 *
 * === 주요 함수/구조체 요약 ===
 * - hweight8(uint8_t w):   0..8  범위의 popcount.
 * - hweight32(uint32_t w): 0..32 범위의 popcount.
 * - hweight64(uint64_t w): 0..64 범위의 popcount. 32비트 빌드에서는 hweight32 두 번 합산.
 * 구조체 없음.
 */
#include "hweight.h"            /* [한국어] 세 함수 프로토타입 + BITS_PER_LONG 매크로 간접 include */

/*
 * [한국어]
 * hweight8 - 8비트 정수의 popcount 를 반환.
 *
 * @w:      0..255 범위의 uint8_t 입력.
 * @return: 0..8 의 설정된 비트 개수.
 *
 * 마스크 상수 풀이:
 *   0x55 = 0101 0101 — 짝수 비트만 선택(각 2비트 쌍의 하위 비트).
 *   0x33 = 0011 0011 — 각 니블(4비트)의 하위 2비트.
 *   0x0F = 0000 1111 — 각 바이트의 하위 니블.
 *
 * 단계 1: res = w - ((w >> 1) & 0x55)
 *   트릭 — 각 2비트 쌍 ab 에 대해 (2a+b) - a = a+b 가 되어 "쌍 내부에 popcount" 저장.
 * 단계 2: res = (res & 0x33) + ((res >> 2) & 0x33)
 *   인접 2비트 쌍 두 개의 popcount 를 더해 니블별 누계(0..4) 로 만든다.
 *   전체 popcount 가 4 이하이므로 각 니블 4비트에 안전히 들어감.
 * 단계 3: (res + (res >> 4)) & 0x0F
 *   두 니블의 popcount 합을 하위 니블에 담고 마스크로 추출 → 최종 0..8.
 *
 * 호출 체인: verify.c(비트 에러 진단 등) → [hweight8].
 * 실행 컨텍스트: 순수 계산, 상태 없음 — 어디서나 호출 안전.
 */
unsigned int hweight8(uint8_t w)
{
	/* [한국어] 단계 1: 2비트 쌍 내부 popcount (w - ((w>>1)&0x55)) */
	unsigned int res = w - ((w >> 1) & 0x55);

	/* [한국어] 단계 2: 니블(4b) 합산 — 2비트 쌍 두 개 더해 0..4 결과 */
	res = (res & 0x33) + ((res >> 2) & 0x33);
	/* [한국어] 단계 3: 상/하 니블 합산 후 하위 4비트만 추출 → 최종 0..8 */
	return (res + (res >> 4)) & 0x0F;
}

/* [한국어] hweight32 - 32비트 popcount. hweight8 과 동일 SWAR 알고리즘의 32비트 확장.
 * 마스크는 같은 패턴을 32비트로 반복(0x55555555, 0x33333333, 0x0F0F0F0F). */
unsigned int hweight32(uint32_t w)
{
	/* [한국어] 단계 1: 각 2비트 쌍 내부 popcount. 모든 2비트 쌍에 대해 병렬 처리 */
	unsigned int res = w - ((w >> 1) & 0x55555555);

	/* [한국어] 단계 2: 니블(4b) 단위 합산 — 0..4 씩 니블당 저장 */
	res = (res & 0x33333333) + ((res >> 2) & 0x33333333);
	/* [한국어] 단계 3: 상/하 니블 합산 후 바이트 단위로 마스킹 → 각 바이트 0..8 */
	res = (res + (res >> 4)) & 0x0F0F0F0F;
	/* [한국어] 단계 4: 상/하 16비트 합산 (아직 오버플로우 안전 — 각 바이트 최대 8) */
	res = res + (res >> 8);
	/* [한국어] 단계 5: 상/하 32비트 합산 후 최하위 8비트만 추출 → 최종 0..32 */
	return (res + (res >> 16)) & 0x000000FF;
}

/*
 * [한국어]
 * hweight64 - 64비트 정수의 popcount 반환 (0..64).
 *
 * 32비트 타겟에서는 64비트 산술 에뮬레이션 오버헤드를 피하기 위해
 * 상/하 32비트를 분리해 hweight32 두 번으로 계산(컴파일러가 좋은 코드 생성).
 * 64비트 타겟에서는 SWAR 을 64비트 상수로 확장하여 단일 경로로 수행.
 *
 * 마스크 풀이(64b):
 *   0x5555...5555 (0x5555555555555555ULL) — 모든 2비트 쌍의 하위 비트.
 *   0x3333...3333 (0x3333333333333333ULL) — 모든 니블의 하위 2비트.
 *   0x0F0F...0F0F (0x0F0F0F0F0F0F0F0FULL) — 모든 바이트의 하위 니블.
 *
 * 호출 체인: lib/axmap.c(비트맵 팝카운트), verify.c 등 → [hweight64].
 */
unsigned int hweight64(uint64_t w)
{
#if BITS_PER_LONG == 32
	/* [한국어] 32비트 빌드: 64b 산술 에뮬 오버헤드 회피를 위해 상/하 32b 를 각각 32b 경로로 처리 */
	return hweight32((unsigned int)(w >> 32)) + hweight32((unsigned int)w);
#else
	/* [한국어] 단계 1: 64b 병렬 2비트 쌍 popcount */
	uint64_t res = w - ((w >> 1) & 0x5555555555555555ULL);
	/* [한국어] 단계 2: 니블 합산 */
	res = (res & 0x3333333333333333ULL) + ((res >> 2) & 0x3333333333333333ULL);
	/* [한국어] 단계 3: 바이트 단위 합산 + 니블 마스크 (각 바이트 0..8) */
	res = (res + (res >> 4)) & 0x0F0F0F0F0F0F0F0FULL;
	/* [한국어] 단계 4: 인접 바이트 쌍 합산 (오버플로우 안전 — 각 바이트 최대 8 → 쌍당 최대 16) */
	res = res + (res >> 8);
	/* [한국어] 단계 5: 인접 워드(16b) 합산 */
	res = res + (res >> 16);
	/* [한국어] 단계 6: 상/하 32b 합산 후 최하위 8비트만 추출 → 최종 0..64 */
	return (res + (res >> 32)) & 0x00000000000000FFULL;
#endif
}
